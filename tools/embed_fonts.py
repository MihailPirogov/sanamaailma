#!/usr/bin/env python3
"""fonts/*.woff2 -> css/fonts.css with base64 data URIs (so fonts also work when index.html is opened from file://)."""
import base64, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = '/* Generated by tools/embed_fonts.py. Manrope, Unbounded: SIL Open Font License 1.1 (fonts/OFL-*.txt). Subset: Latin-1 (ä ö å), Cyrillic. */\n'
for fam, w in (('Manrope', '200 800'), ('Unbounded', '200 900')):
    b = base64.b64encode(open(f'{R}/fonts/{fam}.woff2', 'rb').read()).decode()
    out += f'@font-face{{font-family:"{fam}";src:url(data:font/woff2;base64,{b}) format("woff2");font-weight:{w};font-display:swap}}\n'
open(f'{R}/css/fonts.css', 'w').write(out)
print('css/fonts.css', len(out))
